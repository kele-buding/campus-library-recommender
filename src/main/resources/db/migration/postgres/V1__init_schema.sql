-- 严格对照《概要设计文档》5.2 节物理数据结构设计
-- =====================================================================

-- 1. 专业表（major）
CREATE TABLE major (
    major_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(32) NOT NULL UNIQUE, -- 专业简称，如 SE、IM
    name     VARCHAR(64) NOT NULL UNIQUE  -- 专业名称，如 软件工程、信息管理
);

-- 2. 账号表（account）：四角色统一建表，学生关联专业与试验代号
CREATE TABLE account (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_name    VARCHAR(64)  NOT NULL UNIQUE,
    password_hash VARCHAR(256) NOT NULL,
    role          VARCHAR(32)  NOT NULL CHECK (role IN ('student', 'librarian', 'buyer', 'sysadmin')),
    major_id      BIGINT       REFERENCES major (major_id),
    display_code  VARCHAR(32)  UNIQUE,    -- 试验学生代号，如 A1~A6
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_account_major_id ON account (major_id);
CREATE INDEX idx_account_role ON account (role);

-- 3. 馆藏书目表（book）：version 在每次借出、归还、预约、取消成功后递增
CREATE TABLE book (
    book_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(200) NOT NULL,
    category        VARCHAR(64)  NOT NULL,
    total_count     INTEGER      NOT NULL CHECK (total_count >= 0),
    available_count INTEGER      NOT NULL CHECK (available_count >= 0 AND available_count <= total_count),
    version         BIGINT       NOT NULL DEFAULT 1 CHECK (version >= 0),
    cover_asset_id  BIGINT       -- 封面创建后回绑，见下方外键
);
CREATE INDEX idx_book_category ON book (category);

-- 4. 对象存储素材元数据表（asset）：二进制文件存华为云 OBS，数据库仅存对象键
CREATE TABLE asset (
    asset_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id       BIGINT       NOT NULL REFERENCES book (book_id) ON DELETE CASCADE,
    kind          VARCHAR(32)  NOT NULL CHECK (kind IN ('cover', 'attachment')),
    object_key    VARCHAR(255) NOT NULL UNIQUE,
    original_name VARCHAR(255) NOT NULL,
    content_type  VARCHAR(128) NOT NULL
);
CREATE INDEX idx_asset_book_id ON asset (book_id);

ALTER TABLE book
    ADD CONSTRAINT fk_book_cover_asset
    FOREIGN KEY (cover_asset_id) REFERENCES asset (asset_id) ON DELETE SET NULL;

-- 5. 借阅记录表（loan）：returned_on 为空表示“在借”
CREATE TABLE loan (
    loan_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  BIGINT NOT NULL REFERENCES account (user_id),
    book_id     BIGINT NOT NULL REFERENCES book (book_id),
    borrowed_on DATE   NOT NULL,
    due_on      DATE   NOT NULL,
    returned_on DATE,
    CONSTRAINT ck_loan_returned_gte_borrowed CHECK (returned_on IS NULL OR returned_on >= borrowed_on)
);
CREATE INDEX idx_loan_book_id ON loan (book_id);
-- 部分唯一索引：同一学生对同一书目最多只有 1 条“在借”记录（PostgreSQL 核心特性）
CREATE UNIQUE INDEX uq_loan_active_student_book
    ON loan (student_id, book_id)
    WHERE returned_on IS NULL;
-- 部分索引：加速到期提醒扫描所有在借记录
CREATE INDEX idx_loan_active_due
    ON loan (due_on, loan_id)
    WHERE returned_on IS NULL;

-- 6. 预约表（reservation）：cancelled_at 为空表示“有效预约”
CREATE TABLE reservation (
    reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id     BIGINT      NOT NULL REFERENCES account (user_id),
    book_id        BIGINT      NOT NULL REFERENCES book (book_id),
    created_at     TIMESTAMPTZ NOT NULL,
    cancelled_at   TIMESTAMPTZ
);
-- 部分唯一索引：同一学生对同一书目最多只有 1 条有效预约
CREATE UNIQUE INDEX uq_res_active_student_book
    ON reservation (student_id, book_id)
    WHERE cancelled_at IS NULL;
CREATE INDEX idx_res_active_book
    ON reservation (book_id)
    WHERE cancelled_at IS NULL;

-- 7. 云端采购建议结果表（purchase_result）：与 book.version 比对防止旧结果覆盖
CREATE TABLE purchase_result (
    book_id       BIGINT      PRIMARY KEY REFERENCES book (book_id) ON DELETE CASCADE,
    version       BIGINT      NOT NULL,
    suggested_qty INTEGER     NOT NULL CHECK (suggested_qty >= 0),
    computed_at   TIMESTAMPTZ NOT NULL
);

-- 8. 实验时钟配置表（clock_setting）：全局仅一行（singleton_id = 1）
CREATE TABLE clock_setting (
    singleton_id  SMALLINT DEFAULT 1 PRIMARY KEY,
    sim_date      DATE,
    clock_version BIGINT   NOT NULL DEFAULT 1
);

-- 9. 到期提醒标记表（reminder）：每笔借阅至多 1 条记录，保证定时/手工重复触发幂等
CREATE TABLE reminder (
    loan_id       BIGINT PRIMARY KEY REFERENCES loan (loan_id) ON DELETE CASCADE,
    marked_on     DATE   NOT NULL,
    clock_version BIGINT NOT NULL
);

-- 10. 相似推荐快照表（recommendation_snapshot）：10 分钟有效，保证页面与 CSV 导出一致
CREATE TABLE recommendation_snapshot (
    snapshot_id UUID        PRIMARY KEY,
    student_id  BIGINT      NOT NULL REFERENCES account (user_id) ON DELETE CASCADE,
    payload     JSONB       NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at  TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_rec_snapshot_expires_at ON recommendation_snapshot (expires_at);

-- 11. 写操作幂等回执表（request_receipt）：防止并发重试导致重复扣减库存
CREATE TABLE request_receipt (
    receipt_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id     BIGINT       NOT NULL REFERENCES account (user_id) ON DELETE CASCADE,
    operation    VARCHAR(64)  NOT NULL,
    request_id   UUID         NOT NULL,
    payload_hash VARCHAR(128) NOT NULL,
    response     JSONB        NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_request_receipt_key UNIQUE (actor_id, operation, request_id)
);

-- 12. 审计日志表（audit_log）
CREATE TABLE audit_log (
    log_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id   BIGINT       REFERENCES account (user_id) ON DELETE SET NULL,
    action     VARCHAR(64)  NOT NULL,
    resource   VARCHAR(128) NOT NULL,
    outcome    VARCHAR(64)  NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_audit_log_created_at ON audit_log (created_at);

-- 13. 初始化样例版本记录表（DU-10 幂等装载保护）
CREATE TABLE dataset_seed_state (
    singleton_id    SMALLINT    DEFAULT 1 PRIMARY KEY,
    dataset_version VARCHAR(64) NOT NULL,
    seeded_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
